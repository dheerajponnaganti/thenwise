  const dbFile = join(mkdtempSync(join(tmpdir(), 'thenwise-v6-')), 'g.db')
  const g = new DatabaseSync(dbFile)
  g.exec(`CREATE TABLE nodes(id TEXT PRIMARY KEY, kind TEXT NOT NULL, title TEXT, text TEXT, at TEXT, until TEXT, project TEXT, source TEXT, extra TEXT);
CREATE TABLE edges(src TEXT NOT NULL, dst TEXT NOT NULL, kind TEXT NOT NULL, at TEXT, extra TEXT, PRIMARY KEY(src, dst, kind));`)
  const node = (id: string, kind: string, title: string, at: string, extra: object = {}) => g.prepare('INSERT INTO nodes VALUES (?,?,?,?,?,?,?,?,?)').run(id, kind, title, '', at, '', 'proj', '', JSON.stringify(extra))
  node('pr:proj#1', 'pr', 'One', '2026-10-01T00:00:00Z', { state: 'MERGED' })
  node('pr:proj#2', 'pr', 'Two', '2026-10-02T00:00:00Z', { state: 'MERGED' })
  for (const [i, name] of ['src/a:b.ts', 'src/a?b.ts', 'CON', 'x'.repeat(300), 'x'.repeat(300) + 'y'].entries()) {
    node(`file:/home/proj/${i}`, 'file', name, '', { aliases: [name] })
    g.prepare('INSERT INTO edges VALUES (?,?,?,?,?)').run(`pr:proj#${(i % 2) + 1}`, `file:/home/proj/${i}`, 'touches', '', '{}')
  }
  buildPassageIndex(g)
  g.close()
  const out = mkdtempSync(join(tmpdir(), 'thenwise-out-'))
  const cfg = { memDir: '', vaults: [], viewProjects: [], off: false, offProjects: [], vault: { place: 'central', layout: 'shared', path: out, commit: false } } as any
