const SECRET = 'sk-ant-api03-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA'
const tree = (d: string): Record<string, string> => Object.fromEntries((existsSync(d) ? (readdirSync(d, { recursive: true, withFileTypes: true }) as any[]) : []).filter((e) => e.isFile()).map((e) => [join(e.parentPath, e.name).slice(d.length + 1), readFileSync(join(e.parentPath, e.name), 'utf8')]))
const notesOf = (d: string) => Object.fromEntries(Object.entries(tree(d)).filter(([k]) => k.endsWith('.md') && !k.startsWith('.edited')))

/** A world with chats, decisions and a dead end in git, and a separate output vault. */
function setup(layout = 'shared') {
  const w = new World()
  w.chat('c1', { turns: [{ prompt: 'zebra unicorn passage about the exporter', reply: 'secret reply wibblewobble', edits: [join(w.proj, 'src/a.ts')] }] })
  w.commit(w.proj, 'src/a.ts', 'Pick eight shards', `Decision: keep eight shards\nWhy: fewer locks\nDead-end: one big lock ${SECRET}`)
  w.archive()
  w.ingest('graph.db')
  const out = mkdtempSync(join(tmpdir(), 'thenwise-out-'))
  const cfg = { ...w.cfg, memDir: w.home, vault: { place: 'central', layout, path: out, commit: false } }
  return { w, out, dir: join(out, '_thenwise'), cfg, write: (now?: Date) => writeVault(cfg, { db: w.path('graph.db'), now }) }
}

test('V-H1: decisions, dead ends, timeline and file histories, each with a banner and a format version', () => {
  const { out, dir, write } = setup()
  const r = write()
  assert.equal(r.stopped, undefined)
  const files = Object.keys(notesOf(dir))
  for (const f of ['Decisions.md', 'Dead ends.md', 'Timeline.md', 'Index.md']) assert.ok(files.includes(f), f)
  assert.ok(files.some((f) => f.startsWith('Files/')))
  for (const [f, t] of Object.entries(notesOf(dir))) {
    const fm = parseFrontMatter(t)
    assert.equal(fm.data.thenwise, VAULT_FORMAT, f)
    assert.match(fm.body.trimStart(), /^> Generated by Thenwise\. It is rewritten/, f)
  }
  assert.match(notesOf(dir)['Decisions.md']!, /keep eight shards.*Why: fewer locks/)
  assert.deepEqual(readdirSync(out).filter((f) => f !== '_thenwise'), [])
})

test('V-H2: a folder per project when the layout says so, one set otherwise', () => {
  const per = setup('per-project')
  per.write()
  const dirs = readdirSync(per.dir, { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('.')).map((e) => e.name)
  assert.ok(dirs.length >= 1)
  assert.ok(existsSync(join(per.dir, dirs[0]!, 'Decisions.md')))
  assert.ok(!existsSync(join(per.dir, 'Decisions.md')))
  const shared = setup('shared')
  shared.write()
  assert.ok(existsSync(join(shared.dir, 'Decisions.md')))
})

test('V-H3: frontmatter is valid and every wiki link resolves', () => {
  for (const layout of ['shared', 'per-project']) {
    const { out, dir, write } = setup(layout)
    write()
    const all = notesOf(dir)
    for (const [f, t] of Object.entries(all)) {
      const fm = parseFrontMatter(t)
      assert.deepEqual(fm.issues, [], f)
      assert.ok(Array.isArray(fm.data.sources), f)
      for (const m of t.matchAll(/\[\[([^\]|]+)(?:\|[^\]]*)?\]\]/g)) assert.ok(existsSync(join(out, `${m[1]}.md`)), `${f} links to ${m[1]}`)
    }
  }
})

test('V-H4: a second run changes nothing and equals a fresh write', () => {
  const a = setup()
  a.write()
  const first = tree(a.dir)
  const r = a.write()
  assert.equal(r.written, 0)
  assert.equal(r.unchanged, r.notes)
  assert.deepEqual(tree(a.dir), first)
  rmSync(a.dir, { recursive: true })
  assert.deepEqual(tree(a.dir), {})
  a.write()
  assert.deepEqual(tree(a.dir), first)
})

test('V-H5: today\'s graph.db without a format entry keeps working and gives the same answers', () => {
  const { w } = setup()
  const answers = () => {
    const g = new Graph(w.path('graph.db'))
    const out = ['billing exporter', 'a.ts', 'eight shards'].flatMap((q) => [c.search(g, q), c.current(g, q), c.why(g, q), c.tried(g, q)])
    g.db.close()

    return out
  }
  const before = answers()
  const db = new DatabaseSync(w.path('graph.db'))
  db.exec("DELETE FROM meta WHERE key = 'format'")
  db.close()
  assert.equal(storeFormat(w.path('graph.db')), 1)
  // Format 1 is older than today's (emoji indexing), so the store is rebuilt once and answers the same.
  assert.notEqual(w.ingest('graph.db').mode, 'unchanged')
  assert.equal(storeFormat(w.path('graph.db')), STORE_FORMAT)
  assert.deepEqual(answers(), before)
})

test('V-H6: user notes are read, never changed, and the writer does not read its own notes', () => {
  const { w, cfg } = setup()
  const vcfg = { ...cfg, vault: { ...cfg.vault, path: w.vault } }
  const hash = () => JSON.stringify(Object.entries(tree(w.vault)).filter(([k]) => !k.startsWith('_thenwise')))
  const before = hash()
  const r = writeVault(vcfg, { db: w.path('graph.db') })
  assert.equal(r.stopped, undefined)
  assert.equal(hash(), before)
  assert.ok(existsSync(join(w.vault, '_thenwise/Decisions.md')))
  w.ingest('graph.db')
  const ids = (new DatabaseSync(w.path('graph.db')).prepare("SELECT id FROM nodes WHERE kind IN ('note', 'section')").all() as { id: string }[]).map((x) => x.id)
  assert.ok(ids.some((i) => i.includes('Plan.md')))
  assert.ok(!ids.some((i) => i.includes('_thenwise')))
})

