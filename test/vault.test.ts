test('V-B6: unsafe titles get safe file names without collisions', () => {
  const bad = ['a:b?c/d', 'x'.repeat(300), 'CON', 'con.txt', 'NUL', 'LPT1', 'trailing dot.', '..hidden', '', 'a/b', 'a:b']
  const names = bad.map(safeName)
  for (const n of names) {
    assert.ok(!/[\\/:*?"<>|#^[\]]/.test(n), n)
    assert.ok(n.length <= 101, n)
    assert.ok(!/^(con|prn|aux|nul|com\d|lpt\d)$/i.test(n.split('.')[0]!), n)
    assert.ok(!/[. ]$/.test(n) && !n.startsWith('.'), n)
  }
  // Two files whose names clean to the same text still get two notes.
  const dbFile = join(mkdtempSync(join(tmpdir(), 'thenwise-v6-')), 'g.db')
  const g = new DatabaseSync(dbFile)
  g.exec(`CREATE TABLE nodes(id TEXT PRIMARY KEY, kind TEXT NOT NULL, title TEXT, text TEXT, at TEXT, until TEXT, project TEXT, source TEXT, extra TEXT);
CREATE TABLE edges(src TEXT NOT NULL, dst TEXT NOT NULL, kind TEXT NOT NULL, at TEXT, extra TEXT, PRIMARY KEY(src, dst, kind));`)
  const node = (id: string, kind: string, title: string, at: string, extra: object = {}) => g.prepare('INSERT INTO nodes VALUES (?,?,?,?,?,?,?,?,?)').run(id, kind, title, '', at, '', 'proj', '', JSON.stringify(extra))
  node('pr:proj#1', 'pr', 'One', '2026-10-01T00:00:00Z', { state: 'MERGED' })
  node('pr:proj#2', 'pr', 'Two', '2026-10-02T00:00:00Z', { state: 'MERGED' })
  for (const [i, name] of ['src/a:b.ts', 'src/a?b.ts', 'CON', 'x'.repeat(300), 'x'.repeat(300) + 'y'].entries()) {
    node(`file:/home/proj/${i}`, 'file', name, '', { aliases: [name] })
    g.prepare('INSERT INTO edges VALUES (?,?,?,?,?)').run(`pr:proj#${(i % 2) + 1}`, `file:/home/proj/${i}`, 'touches', '', '{}')
  }
  buildPassageIndex(g)
  g.close()
  const out = mkdtempSync(join(tmpdir(), 'thenwise-out-'))
  const cfg = { memDir: '', vaults: [], viewProjects: [], vault: { place: 'central', layout: 'shared', path: out, commit: false } } as any
  const r = writeVault(cfg, { db: dbFile })
  assert.equal(r.stopped, undefined)
  const files = Object.keys(notesOf(join(out, '_thenwise'))).filter((f) => f.startsWith('Files/'))
  assert.equal(files.length, 5)
  assert.equal(new Set(files.map((f) => f.toLowerCase())).size, 5)
})

test('V-B7: many projects stay under the note cap; rebuild time is recorded', () => {
  const dbFile = join(mkdtempSync(join(tmpdir(), 'thenwise-v7-')), 'g.db')
  const g = new DatabaseSync(dbFile)
  g.exec(`CREATE TABLE nodes(id TEXT PRIMARY KEY, kind TEXT NOT NULL, title TEXT, text TEXT, at TEXT, until TEXT, project TEXT, source TEXT, extra TEXT);
CREATE TABLE edges(src TEXT NOT NULL, dst TEXT NOT NULL, kind TEXT NOT NULL, at TEXT, extra TEXT, PRIMARY KEY(src, dst, kind));`)
  g.exec('BEGIN')
  const node = g.prepare('INSERT INTO nodes VALUES (?,?,?,?,?,?,?,?,?)')
  const edge = g.prepare('INSERT INTO edges VALUES (?,?,?,?,?)')
  for (let i = 0; i < 2000; i++) {
    const p = `proj${i % 100}`
    node.run(`note:n${i}.md`, 'note', `Note ${i}`, '', '2026-10-01T00:00:00Z', '', 'vault', '', '{}')
    node.run(`pr:${p}#${i}`, 'pr', `PR ${i}`, '', `2026-10-01T00:00:00Z`, '', p, '', '{"state":"MERGED"}')
    node.run(`file:/home/u/${p}/f${i}.ts`, 'file', `f${i}.ts`, '', '', '', '', '', `{"aliases":["src/f${i}.ts"]}`)
    edge.run(`pr:${p}#${i}`, `file:/home/u/${p}/f${i}.ts`, 'touches', '', '{}')
  }
  g.exec('COMMIT')
  buildPassageIndex(g)
  g.close()
  const out = mkdtempSync(join(tmpdir(), 'thenwise-out-'))
  const cfg = { memDir: '', vaults: [], viewProjects: [], vault: { place: 'central', layout: 'per-project', path: out, commit: false } } as any
  const t = Date.now()
  const r = writeVault(cfg, { db: dbFile })
  const ms = Date.now() - t
  console.log(`V-B7: ${r.notes} notes (${r.capped} file histories left out) in ${ms} ms from 2,000 notes and 2,000 PRs`)
  assert.ok(r.notes <= NOTE_CAP, String(r.notes))
  assert.ok(r.capped > 0)
  assert.equal(Object.keys(notesOf(join(out, '_thenwise'))).length, r.notes)
})

test('V-B8: a newer format is refused for the store and for vault notes', () => {
  const { w, dir, write } = setup()
  write()
  const p = join(dir, 'Decisions.md')
  const before = readFileSync(p, 'utf8')
  writeFileSync(p, before.replace('thenwise: 1', 'thenwise: 2'))
  const r = write()
  assert.match(r.stopped!, /newer Thenwise.*Update Thenwise/)
  assert.match(readFileSync(p, 'utf8'), /thenwise: 2/)
  const db = new DatabaseSync(w.path('graph.db'))
  db.exec(`INSERT OR REPLACE INTO meta VALUES ('format', '${STORE_FORMAT + 1}')`)
  db.close()
  assert.throws(() => w.ingest('graph.db'), /newer Thenwise.*Update Thenwise/)
  const old = new DatabaseSync(w.path('graph.db'))
  old.exec("UPDATE meta SET value = '0' WHERE key = 'format'")
  old.close()
  assert.equal(w.ingest('graph.db').mode, 'full')
  assert.equal(storeFormat(w.path('graph.db')), STORE_FORMAT)
})

