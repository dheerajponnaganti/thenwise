test('V-B3: an edited note is saved aside and reported, then rewritten', () => {
  const { dir, write } = setup()
  write()
  const p = join(dir, 'Decisions.md')
  const original = readFileSync(p, 'utf8')
  writeFileSync(p, `${original}\nMy own line.\n`)
  const r = write(new Date('2026-10-24T10:00:00Z'))
  assert.equal(r.saved.length, 1)
  assert.match(r.saved[0]!, /Decisions\.md was edited/)
  assert.match(readFileSync(join(dir, '.edited/Decisions 2026-10-24.md'), 'utf8'), /My own line\./)
  assert.equal(readFileSync(p, 'utf8'), original)
  assert.equal(write().saved.length, 0)
})

test('V-B4: an iCloud conflict copy is not read twice and is reported', () => {
  const { w, dir, cfg, write } = setup()
  write()
  writeFileSync(join(dir, 'Decisions 2.md'), readFileSync(join(dir, 'Decisions.md'), 'utf8'))
  writeFileSync(join(w.vault, 'Plan 2.md'), readFileSync(join(w.vault, 'Plan.md'), 'utf8')) // a copy is a near-identical one
  const r = write()
  assert.ok(r.reported.some((x) => x.includes('conflict copy') && x.includes('Decisions 2.md')))
  assert.ok(existsSync(join(dir, 'Decisions 2.md')))
  assert.ok(skippedNotes([w.vault]).some((x) => x.startsWith('conflict copy') && x.includes('Plan 2.md')))
  w.ingest('graph.db')
  const ids = (new DatabaseSync(w.path('graph.db')).prepare("SELECT id FROM nodes WHERE kind = 'note'").all() as { id: string }[]).map((x) => x.id)
  assert.ok(!ids.some((i) => i.includes('Plan 2')))
  assert.ok(cfg)
})

